const { test } = require('node:test');
const assert = require('node:assert/strict');
const { createHub } = require('../server/classroom-hub');
const { ClassroomSync } = require('../classroom-sync');

test('real HTTP sessions isolate classes and students; retries and deletions are idempotent', async t => {
  const hub = createHub({ teacherSecret: 'teacher-secret' });
  await new Promise((resolve, reject) => { hub.server.once('error', reject); hub.server.listen(0, '127.0.0.1', resolve); });
  t.after(() => hub.server.close());
  const base = `http://127.0.0.1:${hub.server.address().port}`;
  async function post(url, body, token) { const r = await fetch(base + url, { method: 'POST', headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: JSON.stringify(body) }); return [r.status, await r.json()]; }
  const [, teacher] = await post('/teacher', { secret: 'teacher-secret', classId: 'class-a' });
  const [, other] = await post('/teacher', { secret: 'teacher-secret', classId: 'class-b' });
  const [, cap] = await post('/capabilities', { studentId: 'student-a', lessonId: 'lesson-a', deviceId: 'device-a', mode: 'student' }, teacher.token);
  const [, student] = await post('/join', { capability: cap.capability });
  assert.equal((await post('/join', { capability: cap.capability }))[0], 403);
  const [, cap2] = await post('/capabilities', { studentId: 'student-b', lessonId: 'lesson-a', deviceId: 'device-b', mode: 'student' }, teacher.token);
  const [, student2] = await post('/join', { capability: cap2.capability });
  const payload = { id: 'submission-a', classId: 'class-a', studentId: 'student-a', lessonId: 'lesson-a', clipId: 'clip-a', clipData: 'data:video/webm;base64,YQ==', clipExpiresAt: Date.now() + 200000, expiresAt: Date.now() + 100000 };
  const operation = { id: 'operation-a', kind: 'submit', payload };
  assert.equal((await post('/operations', operation, student.token))[0], 200);
  assert.equal((await post('/operations', operation, student.token))[0], 200);
  assert.equal((await post('/operations', { ...operation, payload: { ...payload, clipId: 'other' } }, student.token))[0], 409);
  assert.equal((await post('/operations', { ...operation, id: 'operation-b', payload: { ...payload, id: 'submission-b' } }, student2.token))[0], 403);
  assert.equal((await new ClassroomSync(base, other.token).state()).items.length, 0);
  assert.equal((await new ClassroomSync(base, student2.token).state()).items.length, 0);
  assert.equal((await new ClassroomSync(base, teacher.token).state()).items.length, 1);
  assert.equal((await post('/mode', { deviceId: 'device-a', lessonId: 'lesson-a', mode: 'station' }, student.token))[0], 403);
  assert.equal((await post('/mode', { deviceId: 'device-a', lessonId: 'lesson-a', mode: 'station' }, teacher.token))[0], 200);
  assert.equal((await new ClassroomSync(base, student.token).state()).modes[0].mode, 'station');
  const outbox = { outbox: [{ id: 'delete-a', kind: 'delete', payload: { id: 'submission-a', classId: 'class-a' }, status: 'queued', attempts: 0 }] };
  await new ClassroomSync(base, student.token).sync(outbox, async () => {});
  assert.equal(outbox.outbox[0].status, 'sent');
  assert.equal((await new ClassroomSync(base, teacher.token).state()).items.length, 0);
  assert.equal((await post('/operations', { ...operation, id: 'late-submit' }, student.token))[0], 409);
  const feedback = { id: 'feedback-op', kind: 'feedback', payload: { id: 'feedback-a', classId: 'class-a', studentId: 'student-a', lessonId: 'lesson-a', text: '잘했어요', expiresAt: Date.now() + 100000 } };
  assert.equal((await post('/operations', feedback, student.token))[0], 200);
  assert.equal((await new ClassroomSync(base, student.token).state()).items[0].moderation, 'pending');
  assert.equal((await new ClassroomSync(base, student2.token).state()).items.length, 0);
  assert.equal((await post('/moderate', { id: 'feedback-a', action: 'approve' }, student.token))[0], 403);
  assert.equal((await post('/moderate', { id: 'feedback-a', action: 'approve' }, teacher.token))[0], 200);
  assert.equal((await new ClassroomSync(base, student2.token).state()).items[0].text, '잘했어요');
  assert.equal((await post('/moderate', { id: 'feedback-a', action: 'hide' }, teacher.token))[0], 200);
  assert.equal((await new ClassroomSync(base, student2.token).state()).items.length, 0);
  assert.equal((await post('/operations', { ...feedback, id: 'feedback-op-2', payload: { ...feedback.payload, id: 'feedback-b' } }, student2.token))[0], 403);
  const retryPayload = { ...payload, id: 'submission-retry', clipId: 'clip-retry' };
  const retryState = { submissions: [{ id: 'submission-retry' }], outbox: [{ id: 'retry-op', kind: 'submit', payload: retryPayload, status: 'queued', attempts: 0 }] };
  const dropResponse = async (...args) => { await fetch(...args); throw new Error('response lost'); };
  await new ClassroomSync(base, student.token, dropResponse).sync(retryState, async () => {});
  assert.equal(retryState.outbox[0].status, 'failed');
  assert.equal(retryState.outbox[0].payload.clipData, payload.clipData);
  await new ClassroomSync(base, student.token).sync(retryState, async () => {});
  assert.equal(retryState.outbox[0].status, 'sent');
  assert.equal(retryState.outbox[0].payload.clipData, undefined);
  assert.equal((await new ClassroomSync(base, teacher.token).state()).items.filter(item => item.id === 'submission-retry').length, 1);
  const client2 = new ClassroomSync(base, student2.token);
  await client2.logout();
  const loggedOut = await fetch(base + '/state', { headers: { authorization: `Bearer ${student2.token}` } });
  assert.equal(loggedOut.status, 401);
});
