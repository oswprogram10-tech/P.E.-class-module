const { withBrowser } = require('./browser-helper.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');

withBrowser(async (page, errors) => {
  await page.locator('#teacherButton').click();
  await page.locator('#unlockPin').fill('123456'); await page.locator('#unlockButton').click();
  await page.locator('#teacherContentPanel').waitFor({ state: 'visible' });
  await page.locator('[data-panel="classroom"]').click();
  await page.locator('#newClassName').fill('PAPS 보고반'); await page.locator('#addClassButton').click();
  await page.waitForFunction(() => classroomUI.state.classes.length === 1);
  await page.locator('#rosterName').fill('보고 학생'); await page.locator('#rosterNumber').fill('1'); await page.locator('#addStudentButton').click();
  await page.waitForFunction(() => classroomUI.state.students.length === 1);
  const studentId = await page.evaluate(() => classroomUI.state.students[0].id);
  await page.selectOption('#measurementStudent', studentId);
  await page.selectOption('#measurementItem', 'grip-strength');
  await page.selectOption('#measurementCriteriaGrade', 'elementary-5');
  await page.selectOption('#measurementCriteriaTarget', 'male');
  await page.locator('#measurementValue').fill('12.3');
  await page.locator('#saveMeasurementButton').click();
  await page.waitForFunction(() => classroomUI.state.measurements.length === 1);
  await page.locator('.classroom-tool').nth(0).locator('summary').click();
  await page.selectOption('#papsReportStudent', studentId);
  await page.selectOption('#papsReportItem', 'grip-strength');
  await page.selectOption('#papsReportGrade', 'elementary-5');
  await page.selectOption('#papsReportTarget', 'male');
  await page.selectOption('#papsReportYear', '2026');
  await page.waitForFunction(() => document.querySelector('#papsTrendOutput')?.textContent.includes('12.3 kg'));
  assert.match(await page.locator('#papsDistributionOutput').textContent(), /1개 수치 기록 분류/);
  assert.match(await page.locator('#papsTrendOutput').textContent(), /MOE-354-2025-03-10-annex4/);
  await page.locator(`#papsExport-${await page.evaluate(() => classroomUI.state.measurements[0].id)}`).check();
  await page.evaluate(() => { window.confirm = () => true; });
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#papsExportButton').click();
  const download = await downloadPromise;
  assert.match(download.suggestedFilename(), /^paps-local-.*\.csv$/);
  const csv = await fs.readFile(await download.path(), 'utf8');
  assert.match(csv, /PAPS 로컬 임시자료/);
  assert.match(csv, /NEIS 양식 아님/);
  assert.match(csv, /12\.3/);
  assert.deepEqual(errors, []);
  console.log('PAPS report scope, authorized grade distribution and confirmed selected-record CSV passed');
}).catch(error => { console.error(error); process.exitCode = 1; });
